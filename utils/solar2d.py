"""
Модуль: solar2d.py
Назначение: Автоматизированный конвейер извлечения ресурсов движка Solar2D (Corona SDK)
            из установочных пакетов APK, распаковки .car-контейнеров и пакетной
            декомпиляции байткода Lua (*.lu -> *.lua).

--- Формат данных и структура ---
• Входные данные: APK-контейнер (ZIP-архив) или скомпилированный архив ресурсов 'resource.car'.
• Промежуточные данные: Байткод Lua (*.lu), временно развернутый на накопителе или в RAM.
• Выходные данные: Восстановленный исходный код (*.lua) в структурированной директории output.

--- Векторы угроз, защита от сбоев и целостность конвейера ---
• Ошибки платформенных блокировок (Windows File Lock): при создании временного файла
  используется дескриптор с явным вызовом close(), иначе subprocess не сможет получить
  доступ к файлу на платформах семейства NT.
• Изоляция сбоев декомпиляции: падение внешнего транслятора на одном поврежденном или
  обфусцированном чанке байткода не прерывает пакетную обработку остальных скриптов.
• Утечка ресурсов памяти (OOM): прямое чтение архива через zip_file.read() без потокового
  дампа загружает файл целиком в RAM; на тяжелых модификациях (>500 МБ) это может вызвать
  сброс процесса ОС по Out-Of-Memory.

--- Edge Cases (Крайние случаи и платформенные баги) ---
• Нарушение стандарта ZIP-путей: спецификация PKWARE жестко закрепляет прямой слэш ('/').
  Использование обратного слэша ('\\') в find_corona_resources делает функцию полностью
  неработоспособной на POSIX-системах и на стандартных архивах Android Gradle Plugin.
• Утечка дискового пространства: временный файл NamedTemporaryFile создается с флагом
  delete=False, перекладывая обязанность по удалению на вызывающую сторону.

--- Порядок инициализации ---
• Зависит от: core.settings.CORONA_ARCHIVER_UTIL (путь к внешней утилите распаковки .car).
• Зависит от: наличия скомпилированного бинарника dr_decompiler_windows.exe в base_path.
"""

# -----------------------------------------------------------------------------
# СИСТЕМНЫЕ ИМПОРТЫ И ЗАВИСИМОСТИ
# -----------------------------------------------------------------------------

from pathlib import Path
from core import settings
import subprocess
import sys
import tempfile
import zipfile


# -----------------------------------------------------------------------------
# Функции
# -----------------------------------------------------------------------------

def run_extract_car(apk_path: Path) -> str | None:
    """
    Извлекает 'assets/resource.car' из APK и сбрасывает его во временный файл ОС для внешней обработки.

    :param apk_path: Путь к исследуемому файлу пакета Android.
    :return: Абсолютный путь к валидному временному файлу .car на диске либо None при отсутствии ресурса.
    """
    with zipfile.ZipFile(apk_path, 'r') as zip_file:
        # Нормализованный путь: строго соответствует структуре каталогов Android APK (assets/resource.car)
        target_path = "assets/resource.car"

        # Предварительная валидация структуры архива: предотвращает выброс исключения KeyError
        # при попытке прочесть несуществующий ключ из таблицы заголовков ZIP.
        if target_path in zip_file.namelist():
            # Потоковое извлечение сырых байтов контейнера Corona SDK
            car_bytes = zip_file.read(target_path)

            # Создание файла в %TEMP%:
            # 1. delete=False — критически важен под Windows: файл не будет уничтожен при закрытии дескриптора,
            #    что позволит дочернему процессу (run_unpack_resource_car) открыть его по полученному пути.
            # 2. suffix=".car" — обеспечивает корректную ассоциацию расширения для внешних CLI-утилит.
            temp_file = tempfile.NamedTemporaryFile(delete=False, suffix=".car")
            temp_file.write(car_bytes)

            # Принудительный сброс файловых буферов и освобождение дескриптора процесса Python:
            # снимает Windows-блокировку Sharing Violation, давая внешнему распаковщику доступ на чтение.
            temp_file.close()

            # Возврат пути: ответственность за итоговое удаление (unlink) переходит к вызывающему модулю
            # resource.car создаётся в %TEMP%. Возвращается путь к нему.
            return temp_file.name

    return None


def run_unpack_car(car_file_path: str, output_folder: str) -> None:
    """
    Запускает внешний CLI-распаковщик для развертывания бинарного архива Corona (.car).

    Внутренняя логика: утилита разворачивает бинарные чанки ресурсов и предварительно
    скомпилированные файлы скриптов Corona SDK в файловую систему.

    :param car_file_path: Абсолютный или относительный путь к входному .car-файлу.
    :param output_folder: Каталог назначения (создается автоматически со всеми родителями).
    :raises subprocess.CalledProcessError: Если распаковщик завершился с ненулевым кодом (битый архив/нехватка прав).
    """
    # Идемпотентная подготовка файловой системы: предотвращает аварийное завершение утилиты
    # распаковки, если целевая папка отсутствует или уже была создана предыдущими запусками.
    Path(output_folder).mkdir(parents=True, exist_ok=True)

    # Формирование аргументов запуска:
    # 1. sys.executable гарантирует запуск утилиты в контексте текущего активного виртуального окружения (venv).
    # 2. Флаг "-u" переводит архиватор в режим распаковки (unpack).
    # 3. f"{output_folder}/": архитектурный хак Corona CLI — хвостовой пробел со слэшем предотвращает
    #    ошибку конкатенации путей внутри парсера утилиты и гарантирует развертывание в корень целевой папки.
    input_dir = Path(settings.DECOMPILE_LUA_DIR) / "input"
    command = [
        sys.executable,
        str(settings.CORONA_ARCHIVER_UTIL),
        "-u",
        car_file_path,
        # f"{output_folder}/"
        input_dir
    ]

    # Синхронное выполнение: блокирует поток до завершения распаковки;
    # check=True гарантирует немедленный выброс исключения при сбое распаковки,
    # не позволяя пайплайну передавать пустую директорию на шаг декомпиляции.
    subprocess.run(command, check=True)


def run_decompile_lu() -> None:
    """
    Выполняет пакетную обработку и восстановление исходного кода Lua из файлов .lu.

    Внутренняя логика: итерирует скомпилированные модули движка, прогоняет через
    нативный транслятор dr_decompiler и сохраняет результат в зеркальную структуру .lua.

    :param base_path: Базовый рабочий каталог инструментария, содержащий бинарник и папки input/output.
    """
    # Принудительная нормализация типа к Path: защищает от ошибок конкатенации строк
    # и обеспечивает кроссплатформенную совместимость работы с путями.
    base_dir = Path(settings.DECOMPILE_LUA_DIR)
    input_dir = base_dir / "input"
    output_dir = base_dir / "output"
    decompiler_exe = base_dir / "dr_decompiler_windows.exe"

    # Защита от сбоя декомпилятора: гарантирует существование выходного буфера до старта внешнего процесса.
    output_dir.mkdir(parents=True, exist_ok=True)

    # Жадная материализация генератора в список: фиксирует срез файлов на момент запуска,
    # предотвращая бесконечные циклы или пропуски при динамическом изменении каталога input.
    lu_files = list(input_dir.glob("*.lu"))

    # Паттерн Early Exit: исключает бессмысленную аллокацию системных процессов,
    # если директория пуста или предыдущий шаг распаковки не выдал байткод.
    if not lu_files:
        print("Файлы .lu не найдены в папке input.")
        return

    # Пакетная обработка независимых модулей
    for lu_file in lu_files:
        # Здесь должна быть проверка файлов на необходимые:
        # Нужные файлы декомпилируем, а лишние удаляем

        # Сохранение исходного стема (.stem) критично для моддинга: движок Solar2D
        # осуществляет поиск зависимостей через require("module_name"), поэтому изменение имени нарушит резолвинг.
        output_lua = output_dir / f"{lu_file.stem}.lua"

        # Формирование аргументов CLI нативного декомпилятора:
        # "decompile" — сервисный режим трансляции опкодов Lua в читаемый синтаксический AST.
        command = [
            str(decompiler_exe),
            "decompile",
            str(lu_file),
            str(output_lua)
        ]

        try:
            # Изолированный вызов бинарника: подавляет падение всей очереди при локальном сбое
            subprocess.run(command, check=True)
            # print(f"Декомпилирован: {lu_file.name}")
        except subprocess.CalledProcessError as e:
            # Локальная деградация: если конкретный .lu файл содержит поврежденные опкоды,
            # обфускацию или невалидные заголовки Lua, логируем ошибку и продолжаем декомпиляцию остальных файлов.
            print(f"Ошибка при декомпиляции {lu_file.name}: {e}")
        except FileNotFoundError:
            # Критический сбой окружения: если сам исполняемый файл декомпилятора удален или заблокирован антивирусом,
            # продолжать цикл бессмысленно — прерываем выполнение всего конвейера (break).
            print(f"Критическая ошибка: {decompiler_exe.name} не найден!")
            break


def run_clear_decompiler(folder_name: str):
    # Формируем путь без двойного оборачивания
    target_dir = Path(settings.DECOMPILE_LUA_DIR) / folder_name

    # Ищем все файлы с расширением .lua
    for lua_file in target_dir.glob("*.lua"):
        # Убеждаемся, что это файл, а не директория
        if lua_file.is_file():
            # missing_ok=True (Python 3.8+) предотвращает ошибку,
            # если файл был удален другой программой за долю секунды до этого
            lua_file.unlink(missing_ok=True)

